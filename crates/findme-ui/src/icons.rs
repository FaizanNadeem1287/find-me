/// Renders a resolution-independent vector SVG icon with dynamic theme color tinting
pub fn icon<'a, Message: 'a>(name: Icon, size: f32, color: Color) -> Element<'a, Message> {
    iced::widget::svg(Handle::from_memory(name.svg_str().as_bytes()))
        .width(Length::Fixed(size))
        .height(Length::Fixed(size))
        .style(move |_theme, _status| svg::Style { color: Some(color) })
        .into()
}
